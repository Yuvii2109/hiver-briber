import pandas as pd, numpy as np, re
df=pd.read_pickle('data/raw/twcs_threaded.pkl'); df['inbound']=df['inbound'].astype(bool)
bo=df.loc[~df.inbound].groupby('thread')['author_id'].first()
th=set(bo[bo=='AmericanAir'].index)
d=df[df.thread.isin(th)].copy()
d['created']=pd.to_datetime(d['created_at'],format='%a %b %d %H:%M:%S %z %Y',errors='coerce')
d=d.sort_values(['thread','created'])
DEFL=re.compile(r'(?:\bdm\b|\bdms\b|direct message|private message|send us a (?:note|message|dm)|message us|follow up (?:here|with us)|contact us|reach out|email us|(?:visit|click|head (?:to|over)|fill out|complete)[^.!?]{0,40}https?://)',re.I)
def strip(s):
    s=re.sub(r'https?://\S+','',str(s)); s=re.sub(r'@\w+','',s)
    s=re.sub(r'[\^\-~]\s?[A-Za-z]{2}\s*$','',s.strip()); return re.sub(r'\s+',' ',s).strip()
out=d[~d.inbound].copy()
out['core']=out['text'].map(strip); out['w']=out['core'].str.split().str.len()
out['defl']=out['text'].str.contains(DEFL); out['ask']=out['core'].str.contains(r'\?')
out['subst']=(~out['defl'])&(~out['ask'])&(out['w']>=8)
first=out.groupby('thread').first()
per=out.groupby('thread').agg(any_subst=('subst','any'))
print(f"AA threads={len(th):,}  brand replies={len(out):,}")
print(f"  ALL replies:   defl={100*out.defl.mean():.1f}%  ask-only={100*(out.ask&~out.defl).mean():.1f}%  substantive={100*out.subst.mean():.1f}%  median words={out.w.median():.0f}")
print(f"  FIRST reply:   defl={100*first.defl.mean():.1f}%  substantive={100*first.subst.mean():.1f}%")
print(f"  threads with ANY substantive brand reply: {100*per.any_subst.mean():.1f}%")
dt=set(first[first.defl].index); sp=set(per[per.any_subst].index)
print(f"  rescue: of first-reply-deflection threads, {100*len(dt&sp)/max(len(dt),1):.1f}% later contain a substantive reply")
# how many reference replies are SHORT non-answers
print(f"  replies <=8 words (core): {100*(out.w<=8).mean():.1f}%   <=5 words: {100*(out.w<=5).mean():.1f}%")
print("\n--- sample FIRST replies that deflect ---")
for s in first[first.defl]['text'].sample(6,random_state=1): print("  *",strip(s)[:150])
print("\n--- sample FIRST replies that are substantive ---")
for s in first[first.subst]['text'].sample(6,random_state=1): print("  *",strip(s)[:150])
