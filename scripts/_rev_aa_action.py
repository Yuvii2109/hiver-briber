import pandas as pd, re, collections, numpy as np, time
t0=time.time()
df=pd.read_pickle('data/raw/twcs_threaded.pkl'); df['inbound']=df['inbound'].astype(bool)
ob=df[(~df.inbound)&(df.author_id.isin(['AmericanAir','Delta','Uber_Support']))].sort_values(['thread','created_at'])
first=ob.groupby(['author_id','thread'],as_index=False).first()
print("rows",len(first),time.time()-t0,flush=True)
APOL=re.compile(r"\b(sorry|apolog|regret|unfortunate)\b",re.I)
ACT=re.compile(r"\b(rebook|rebooked|reboard|gate|check[- ]?in|boarding pass|baggage claim|bag(gage)? (tag|trace|claim)|file a claim|refund|voucher|credit|miles|upgrade|standby|seat|reservations at|call \d|aa\.com|delta\.com|link|form|desk|agent at|record locator|confirmation number|reissue|waiver|compensat)\b",re.I)
DEFL=re.compile(r"\b(dm|direct message|private message|message us|email us)\b",re.I)
for b,g in first.groupby('author_id'):
    t=g['text'].astype(str)
    apol=t.str.contains(APOL); act=t.str.contains(ACT); dfl=t.str.contains(DEFL)
    print(f"\n{b}  n={len(g)}")
    print(f"  contains apology cue      : {100*apol.mean():.1f}%")
    print(f"  contains concrete-action cue: {100*act.mean():.1f}%")
    print(f"  deflect cue               : {100*dfl.mean():.1f}%")
    print(f"  apology-only (no action, no deflect): {100*(apol&~act&~dfl).mean():.1f}%")
    print(f"  action WITHOUT deflect     : {100*(act&~dfl).mean():.1f}%")
    print(f"  neither apology nor action : {100*(~apol&~act).mean():.1f}%")
    print(f"  distinct normalized texts / n : {t.str.lower().str.replace(r'[^a-z ]','',regex=True).nunique()/len(g):.3f}")
print("DONE",time.time()-t0)
